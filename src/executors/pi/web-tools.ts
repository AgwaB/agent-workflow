/**
 * 2026-11-02 (quality A/B rerun): which of Pi's web tools pi-web-access actually registers, and the
 * one fix the engine may apply with the user's consent. pi-web-access reads its own config
 * (`web-search.json`); `tools.<key>.enabled: false` there removes a tool, and Pi then drops the name
 * from `--tools` without a word — a deep-research verifier ran without `fetch_content` and left its
 * claims unverified. The probe lists the registered tools in a Pi session that exits before any model
 * request; the fix flips only that one key, after the user agreed (`agent-workflow doctor --fix`).
 */
import { execFile } from "node:child_process";
import { existsSync } from "node:fs";
import {
	chmod,
	mkdtemp,
	readFile,
	rename,
	rm,
	stat,
	writeFile,
} from "node:fs/promises";
import { homedir, tmpdir } from "node:os";
import { join } from "node:path";

/** Workflow web tool → pi-web-access config key (`DEFAULT_TOOL_NAMES` in its web-tool-core.ts). */
export const PI_WEB_TOOL_CONFIG_KEYS: Readonly<Record<string, string>> = {
	web_search: "webSearch",
	fetch_content: "fetchContent",
};

/** pi-web-access's config path (its utils.ts `getWebSearchConfigDir`, same order). */
export function piWebAccessConfigPath(
	env: NodeJS.ProcessEnv = process.env,
): string {
	const file = "web-search.json";
	if (env.PI_CODING_AGENT_DIR) return join(env.PI_CODING_AGENT_DIR, file);
	const legacy = join(homedir(), ".pi");
	if (env.XDG_CONFIG_HOME) {
		const xdg = join(env.XDG_CONFIG_HOME, "pi");
		if (existsSync(join(xdg, file))) return join(xdg, file);
		if (existsSync(join(legacy, file))) return join(legacy, file);
		return join(xdg, file);
	}
	const agent = join(homedir(), ".pi", "agent");
	if (existsSync(join(agent, file))) return join(agent, file);
	if (existsSync(join(legacy, file))) return join(legacy, file);
	return join(agent, file);
}

/** Why a requested web tool is missing, and what to do (probe `unavailableTools` text). */
export function piWebToolUnavailableGuidance(
	tool: string,
	configPath: string = piWebAccessConfigPath(),
): string {
	const key = PI_WEB_TOOL_CONFIG_KEYS[tool] ?? tool;
	return `pi-web-access is installed but does not register ${tool}: its configuration turns it off (\`tools.${key}.enabled\` in ${configPath}${
		tool === "web_search" ? ", or `webSearch.enabled`" : ""
	}). Turn it on with \`agent-workflow doctor --fix\` (asks before editing that file), edit the file yourself, or run the stage with --executor claude or codex`;
}

const PROBE_EXTENSION = `// Generated by agent-workflow: list the tools this Pi session registers, then exit before any
// model request (no prompt is ever sent to a model).
import { writeFileSync } from "node:fs";
export default function agentWorkflowToolProbe(pi) {
	const dump = () => {
		writeFileSync(process.env.AW_PI_TOOL_PROBE_OUT, JSON.stringify(pi.getAllTools().map((tool) => tool.name)));
		process.exit(0);
	};
	pi.on("session_start", dump);
	pi.on("before_agent_start", dump);
}
`;

/**
 * Tools registered in an isolated Pi session with pi-web-access loaded (the worker's own flags),
 * or null when Pi could not tell. The session exits in `session_start`, before any model request.
 */
export async function listPiWebSessionTools(
	piCommand: string,
	webAccessExtension: string,
	options: { readonly timeoutMs: number },
): Promise<string[] | null> {
	const dir = await mkdtemp(join(tmpdir(), "aw-pi-tool-probe-"));
	try {
		const extension = join(dir, "probe.mjs");
		const out = join(dir, "tools.json");
		await writeFile(extension, PROBE_EXTENSION, { mode: 0o600 });
		await new Promise<void>((resolve) => {
			// Pi in --print mode reads a non-TTY stdin before it starts: close it at once.
			const child = execFile(
				piCommand,
				[
					"--mode",
					"json",
					"--print",
					"--no-session",
					"--no-context-files",
					"--no-extensions",
					"--no-skills",
					"--no-prompt-templates",
					"--no-themes",
					"--no-approve",
					"--tools",
					Object.keys(PI_WEB_TOOL_CONFIG_KEYS).join(","),
					"-e",
					webAccessExtension,
					"-e",
					extension,
					"list tools",
				],
				{
					cwd: dir,
					timeout: options.timeoutMs,
					env: { ...process.env, AW_PI_TOOL_PROBE_OUT: out },
					maxBuffer: 4 * 1024 * 1024,
				},
				() => resolve(),
			);
			child.stdin?.end();
		});
		const names = JSON.parse(await readFile(out, "utf8")) as unknown;
		return Array.isArray(names) &&
			names.every((name) => typeof name === "string")
			? names
			: null;
	} catch {
		return null;
	} finally {
		await rm(dir, { recursive: true, force: true }).catch(() => undefined);
	}
}

export type PiWebToolFixResult =
	| { readonly changed: true; readonly path: string; readonly setting: string }
	| { readonly changed: false; readonly path: string; readonly reason: string };

/**
 * Turn a web tool back on in pi-web-access's config: only `tools.<key>.enabled: false` (and, for
 * web_search, `webSearch.enabled: false`) becomes true; every other value is kept and nothing is
 * printed from the file. Call only after the user agreed.
 */
export async function enablePiWebTool(
	tool: string,
	env: NodeJS.ProcessEnv = process.env,
): Promise<PiWebToolFixResult> {
	const path = piWebAccessConfigPath(env);
	const key = PI_WEB_TOOL_CONFIG_KEYS[tool];
	if (key === undefined)
		return {
			changed: false,
			path,
			reason: `${tool} is not a pi-web-access tool`,
		};
	let config: Record<string, unknown>;
	let mode = 0o600;
	try {
		mode = (await stat(path)).mode & 0o777;
		const parsed = JSON.parse(await readFile(path, "utf8")) as unknown;
		if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed))
			return {
				changed: false,
				path,
				reason: "the config is not a JSON object",
			};
		config = parsed as Record<string, unknown>;
	} catch (error) {
		return {
			changed: false,
			path,
			reason: `the config cannot be read (${(error as NodeJS.ErrnoException).code ?? "invalid JSON"})`,
		};
	}
	const settings: string[] = [];
	const tools = config.tools as Record<string, unknown> | undefined;
	const entry = tools?.[key] as Record<string, unknown> | undefined;
	if (
		entry !== undefined &&
		entry !== null &&
		typeof entry === "object" &&
		entry.enabled === false
	) {
		entry.enabled = true;
		settings.push(`tools.${key}.enabled`);
	}
	const webSearch = config.webSearch as Record<string, unknown> | undefined;
	if (
		tool === "web_search" &&
		webSearch !== undefined &&
		webSearch !== null &&
		typeof webSearch === "object" &&
		webSearch.enabled === false &&
		!(
			entry !== undefined &&
			entry !== null &&
			typeof entry === "object" &&
			"enabled" in entry
		)
	) {
		webSearch.enabled = true;
		settings.push("webSearch.enabled");
	}
	if (settings.length === 0)
		return {
			changed: false,
			path,
			reason: `no \`enabled: false\` setting for ${tool} there; it may be renamed (\`toolNames.${key}\`) — check the file`,
		};
	const temp = `${path}.agent-workflow-${process.pid}.tmp`;
	await writeFile(temp, `${JSON.stringify(config, null, 2)}\n`, { mode });
	await chmod(temp, mode);
	await rename(temp, path);
	return { changed: true, path, setting: settings.join(", ") };
}
